from pathlib import Path
import json
import re

manifest = Path("android/app/src/main/AndroidManifest.xml")
if not manifest.exists():
    raise SystemExit("AndroidManifest.xml was not generated by flutter create.")

text = manifest.read_text(encoding="utf-8")
# This app is designed to work fully offline. Remove network permission.
text = re.sub(
    r'\s*<uses-permission[^>]*android:name="android\.permission\.INTERNET"[^>]*/>',
    '',
    text
)
text = re.sub(r'android:label="[^"]*"', 'android:label="Bible Reading Plan"', text, count=1)
manifest.write_text(text, encoding="utf-8")

# Set a stable Android application ID in the generated Gradle file where supported.
gradle_kts = Path("android/app/build.gradle.kts")
if gradle_kts.exists():
    g = gradle_kts.read_text(encoding="utf-8")
    g = re.sub(r'applicationId\s*=\s*"[^"]+"',
               'applicationId = "com.biblereadingplan.app"', g, count=1)
    gradle_kts.write_text(g, encoding="utf-8")

gradle_groovy = Path("android/app/build.gradle")
if gradle_groovy.exists():
    g = gradle_groovy.read_text(encoding="utf-8")
    g = re.sub(r'applicationId\s+"[^"]+"',
               'applicationId "com.biblereadingplan.app"', g, count=1)
    gradle_groovy.write_text(g, encoding="utf-8")

# Replace the online Bible API reader with the bundled, complete KJV text.
# The 66 book JSON files are packaged in assets/www/kjv, so every passage
# can be opened without an internet connection on the installed app.
web_app = Path("assets/www/index.html")
if web_app.exists():
    html = web_app.read_text(encoding="utf-8")
    start = html.find("async function fetchOnePassage(reference){")
    end = html.find("\nasync function getPassage", start)
    if start < 0 or end < 0:
        raise SystemExit("Could not locate the Bible passage loader in index.html.")
    offline_loader = r"""async function fetchOnePassage(reference){
  const cached=await cacheGet(reference);
  if(cached)return cached;
  const normalized=reference.replace(/:\s*/g,':').replace(/\s+/g,' ').trim();
  const match=normalized.match(/^(.*?)\s+(\d+)(?::(\d+)(?:-(\d+))?)?$/);
  if(!match)throw new Error('This Bible reference could not be understood: '+reference);
  let bookName=match[1].trim();
  if(bookName.toLowerCase()==='psalm')bookName='Psalms';
  const chapterNumber=Number(match[2]);
  const firstVerse=match[3]?Number(match[3]):1;
  const lastVerse=match[4]?Number(match[4]):(match[3]?firstVerse:Infinity);
  const fileName=bookName.replace(/\s+/g,'_');
  // Read from the embedded in-memory KJV dataset; no file fetch or network.
  const bookData=window.__KJV_BOOKS__&&window.__KJV_BOOKS__[fileName];
  if(!bookData)throw new Error('The offline KJV book '+bookName+' is missing from this app.');
  const chapterData=(bookData.chapters||[]).find(c=>Number(c.chapter)===chapterNumber);
  if(!chapterData)throw new Error('Chapter '+chapterNumber+' was not found in '+bookName+'.');
  const verses=(chapterData.verses||[])
    .filter(v=>Number(v.number)>=firstVerse&&Number(v.number)<=lastVerse)
    .map(v=>({book_name:bookData.englishName||bookName,chapter:chapterNumber,verse:Number(v.number),text:v.text}));
  if(!verses.length)throw new Error('No verses were found for '+reference+'.');
  const data={reference,translation_name:'King James Version (KJV)',verses};
  await cachePut(reference,data);
  return data;
}"""
    html = html[:start] + offline_loader + html[end:]

    # Embed the complete KJV dataset into the local HTML document. Android
    # WebView can block fetch() requests to file:// assets even when bundled.
    # A single in-memory JS object makes every book available with no network.
    kjv_dir = Path("assets/www/kjv")
    book_files = sorted(kjv_dir.glob("*.json"))
    if len(book_files) != 66:
        raise SystemExit(f"Expected 66 KJV book files, found {len(book_files)}.")
    kjv_books = {}
    chapter_count = 0
    verse_count = 0
    for book_file in book_files:
        book_data = json.loads(book_file.read_text(encoding="utf-8"))
        kjv_books[book_file.stem] = book_data
        chapter_count += len(book_data.get("chapters", []))
        verse_count += sum(len(ch.get("verses", [])) for ch in book_data.get("chapters", []))
    if chapter_count != 1189 or verse_count != 31102:
        raise SystemExit(
            f"KJV data validation failed: {chapter_count} chapters, {verse_count} verses."
        )

    # Replace any previous generated copy so repeated builds remain clean.
    html = re.sub(
        r'<script id="offline-kjv-data">.*?</script>',
        '',
        html,
        flags=re.DOTALL
    )
    embedded_kjv = (
        '<script id="offline-kjv-data">window.__KJV_BOOKS__ = '
        + json.dumps(kjv_books, ensure_ascii=False, separators=(",", ":"))
        + ';</script>'
    )
    if "</head>" in html:
        html = html.replace("</head>", embedded_kjv + "</head>", 1)
    elif "</body>" in html:
        html = html.replace("</body>", embedded_kjv + "</body>", 1)
    else:
        raise SystemExit("Could not find </head> or </body> to embed offline KJV data.")

    # Remove any external BibleGateway fallback link from the reader error UI.
    html = html.replace(
        "const link=document.createElement('a');link.href='https://www.biblegateway.com/passage/?search='+encodeURIComponent(reference)+'&version=KJV';link.target='_blank';link.rel='noopener';link.textContent='Open this KJV passage in a new tab';box.append(p,link);content.append(box);",
        "box.append(p);content.append(box);"
    )
    if re.search(r'https?://', html):
        raise SystemExit("External URL remains in the app HTML; review before offline release.")

    web_app.write_text(html, encoding="utf-8")


# Work around an Android Gradle Lint runtime crash in webview_flutter_android.
# The release lint task currently crashes inside the Android lint parser before
# reporting any app issue. Skip only lintVital tasks; keep compilation and packaging.
for gradle_file in (Path("android/build.gradle"), Path("android/build.gradle.kts")):
    if gradle_file.exists():
        gradle_text = gradle_file.read_text(encoding="utf-8")
        if "tasks.configureEach" not in gradle_text or "lintVital" not in gradle_text:
            gradle_text += """

// Work around the Android Lint parser runtime failure in webview_flutter_android.
subprojects {
    tasks.configureEach {
        if (name.startsWith("lintVital")) {
            enabled = false
        }
    }
}
"""
            gradle_file.write_text(gradle_text, encoding="utf-8")
